# Pontuação inicial
pontuacao = 100

# Adicionar 50 pontos
pontuacao += 50
print(f"Após adicionar 50 pontos: {pontuacao}")

# Remover 20 pontos
pontuacao -= 20
print(f"Após remover 20 pontos: {pontuacao}")

# Dobrar a pontuação
pontuacao *= 2
print(f"Após dobrar a pontuação: {pontuacao}")

# Dividir a pontuação por 2
pontuacao /= 2
print(f"Após dividir a pontuação por 2: {pontuacao}")